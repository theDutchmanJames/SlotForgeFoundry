// Standard buildings: good starting settings for what slot-racing layouts
// most often have beside the track. Each is an ordinary building, so every
// setting can be changed afterwards. Toy proportions for 1:32.

const window = (wall, at, width, height, sill, frame = true) => ({ wall, type: 'window', at, width, height, sill, frame });
const door = (wall, at, frame = true) => ({ wall, type: 'door', at, width: 28, height: 48, frame });
// A serving hatch: a window with a counter under it and a flap propped open over it.
// A window of panes: its frame split across and up.
const panes = (wall, at, width, height, sill, across, up) => ({ ...window(wall, at, width, height, sill), across, up });
// An opening of a connected section or a shaped building: framed, a window with its panes.
const shell = (wall, type, at, width, height, sill, across = 1, up = 1) => ({ wall, type, at, width, height, sill, frame: true, ...(type === 'window' && { across, up }) });
const hatch = (wall, at, width, height, sill, frame = false) => ({ ...window(wall, at, width, height, sill, frame), counter: true, flap: true });

/** A row of pit garages side by side, one bay each, as many as wanted. */
export function pitRow(bays = 4) {
  return {
    rooms: { along: 'width', sizes: Array.from({ length: bays }, () => 110) },
    depth: 180,
    height: 75,
    doorWidth: 80,
    doorHeight: 55,
    overhangFront: 12,
  };
}

/** A modern pit building: garages below, a glazed lounge above them on a balcony over the pit lane, a roof terrace. */
export function modernPits(bays = 3, depth = 160) {
  const width = bays * 110;
  return {
    ...pitRow(bays),
    depth,
    door: 'panel',
    doorHeight: 52,
    numbers: true,
    wallTexture: 'plain',
    roofRailing: true,
    overhangFront: 2,
    overhangBack: 2,
    overhangLeft: 2,
    overhangRight: 2,
    upper: [
      {
        width,
        depth: depth - 20,
        x: 0,
        y: 0,
        height: 55,
        balcony: 25,
        railing: true,
        openings: Array.from({ length: bays }, (_, i) => window('front', 55 + i * 110, 86, 32, 12)),
      },
    ],
  };
}

