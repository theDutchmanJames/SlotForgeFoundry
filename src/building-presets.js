function lettered(p) {
  const w = WORDS[p.id];
  if (!w) return p;
  let b = { ...p.building, ...(w.signText && { signText: w.signText }), ...w.set };
  if (w.lettering) b = w.storey ? { ...b, upper: b.upper.map((u, i) => (i === w.storey - 1 ? { ...u, lettering: w.lettering } : u)) } : { ...b, lettering: w.lettering };
  return { ...p, building: b };
}
